"""
The live decoder: a headless GNU Radio flowgraph.

The whole signal path is GNU Radio. Samples come off the dongle through
gr-osmosdr, are shifted, filtered and decimated by GNU Radio's own
frequency-translating FIR, and end in the decoder sink:

    RTL-SDR Blog V3  ->  osmosdr.source
                     ->  filter.freq_xlating_fir_filter_ccf (firdes.low_pass)
                     ->  si4463_gr_block.Si4463Sink  ->  stdout + CSV

This is si4463_rpi.grc with the Qt sinks removed, built in Python rather than
generated by GRC so that it runs over SSH and under systemd with no display.
The chain and its numbers are shared with the flowgraph through
si4463_gr_block, so a packet that decodes in one decodes in the other.

Replay (--wav) swaps the osmosdr source for a wavfile_source and changes
nothing else, so the reference capture exercises the exact live chain.

Tuning. The LO is parked --lo-offset above the signal and the translating
filter shifts back down by the same amount, which puts the dongle's DC spike
and its 1/f noise 100 kHz away from the packet instead of underneath it. It
also makes tuner error harmless: the passband reaches 60 kHz, so tens of kHz of
LO error still lands inside it, and the decoder removes what is left burst by
burst. The RTL-SDR Blog V3's 1 ppm TCXO means --ppm 0 is genuinely right at
433 MHz, where 1 ppm is 435 Hz.

Sample rate. The default is 1.2 MS/s rather than 2.4 MS/s. The signal is 45 kHz
wide and the decoder wants 200 kS/s, so 2.4 MS/s only ever bought a longer
filter: the tap count scales with fs/transition, so halving the input rate
halves the work for a signal that was never near Nyquist.

Reliability. Three things are watched from the main thread while the
flowgraph runs, because each of them otherwise looks exactly like a quiet band:

  * Lost samples. The number of samples that reached the decoder is compared
    against the wall clock. If the Pi cannot keep up, librtlsdr's buffers
    overflow and samples vanish upstream; the shortfall is reported.
  * A stalled stream. A dongle that is pulled, browns out or wedges stops
    delivering samples without raising anything. If none arrive for
    --stall-timeout seconds the decoder exits non-zero, so systemd restarts it
    and reopens the device.
  * CPU load. Process CPU time (every GNU Radio thread) per second of signal.

Run it:

    ./si4463_rt.py                       # live, logs to logs/packets_*.csv
    ./si4463_rt.py --wav capture.wav     # replay a baseband recording
    ./si4463_rt.py --list-devices
"""

import argparse
import os
import signal
import sys
import threading
import time
import wave

from gnuradio import blocks, gr
from gnuradio import filter as gr_filter
from gnuradio.filter import firdes

import si4463_csv
from si4463_gr_block import CUTOFF_HZ, TARGET_RATE, TRANSITION_HZ, Si4463Sink


def front_end(rate, shift_hz):
    """The translating decimator every chain in this project uses.

    Returns (block, decimation, output rate, tap count). Kept as one function
    so the live decoder and the benchmark build the identical filter.
    """
    decim = max(1, int(round(rate / TARGET_RATE)))
    taps = firdes.low_pass(1.0, rate, CUTOFF_HZ, TRANSITION_HZ)
    xlate = gr_filter.freq_xlating_fir_filter_ccf(decim, taps, shift_hz, rate)
    return xlate, decim, rate / decim, len(taps)


def osmosdr_source(args):
    """Open and configure the RTL-SDR through gr-osmosdr.

    Every setting is applied explicitly, including the ones whose defaults
    happen to be right, because the R820T2 and the V3's bias tee keep state
    between sessions: a previous program can leave the AGC on or 4.5 V on the
    coax, and the only safe assumption is that it did.
    """
    import osmosdr

    dev = 'rtl=%d,bias=%d' % (args.device_index, 1 if args.bias_tee else 0)
    if args.device_args:
        dev += ',' + args.device_args
    src = osmosdr.source(args='numchan=1 ' + dev)

    src.set_sample_rate(args.rate)
    src.set_center_freq(args.freq + args.lo_offset, 0)
    src.set_freq_corr(args.ppm, 0)
    # DC and IQ correction off: the LO offset already keeps the DC spike away
    # from the packet, and the corrections' tracking loops add nothing here.
    src.set_dc_offset_mode(0, 0)
    src.set_iq_balance_mode(0, 0)
    src.set_gain_mode(bool(args.agc), 0)
    if not args.agc:
        src.set_gain(args.gain, 0)
    src.set_bandwidth(0, 0)
    return src


class Receiver(gr.top_block):
    """Source -> translating decimator -> decoder."""

    def __init__(self, args):
        gr.top_block.__init__(self, 'Si4463 receiver', catch_exceptions=True)
        self.live = not args.wav

        if args.wav:
            with wave.open(args.wav) as w:
                if w.getnchannels() != 2:
                    raise SystemExit(
                        '%s has %d channel(s); a baseband recording needs 2 '
                        '(I and Q).' % (args.wav, w.getnchannels()))
                self.rate = float(w.getframerate())
            wav = blocks.wavfile_source(args.wav, False)
            f2c = blocks.float_to_complex(1)
            self.connect((wav, 0), (f2c, 0))
            self.connect((wav, 1), (f2c, 1))
            src = f2c
            shift = args.wav_offset
        else:
            self.osmo = osmosdr_source(args)
            src = self.osmo
            self.rate = self.osmo.get_sample_rate()
            shift = -args.lo_offset
            self._report_tuning(args)

        xlate, self.decim, self.out_rate, ntaps = front_end(self.rate, shift)
        self.sink = Si4463Sink(
            decim_rate=self.out_rate, symbol_rate=args.baud,
            deviation=args.deviation, packet_len_bytes=args.packet_len,
            burst_threshold_db=args.threshold, heartbeat_s=args.heartbeat,
            csv_path=args.csv)
        self.connect(src, xlate, self.sink)

        print('GNU Radio %s. Chain: %.3f MS/s -> decimate %d -> %.1f kS/s '
              '(%.1f samples/symbol), shift %+.1f kHz, %d filter taps.'
              % (gr.version(), self.rate / 1e6, self.decim,
                 self.out_rate / 1e3, self.out_rate / args.baud, shift / 1e3,
                 ntaps))

    def _report_tuning(self, args):
        src = self.osmo
        if abs(self.rate - args.rate) > 1.0:
            print('!! Asked for %.6f MS/s; the dongle is running %.6f MS/s.'
                  % (args.rate / 1e6, self.rate / 1e6))
            print('   The RTL2832 only supports 225.001-300.000 kS/s and '
                  '0.900001-3.2 MS/s.')
        if args.agc:
            gain_txt = 'AGC'
        else:
            got = src.get_gain(0)
            gain_txt = '%.1f dB' % got
            if abs(got - args.gain) > 0.05:
                gain_txt += (' (asked %.1f, nearest step in the tuner table)'
                             % args.gain)
        print('RTL-SDR: LO %.6f MHz (signal %.6f MHz %+.0f kHz), %.3f MS/s, '
              'gain %s, %+.1f ppm, bias tee %s.'
              % (src.get_center_freq(0) / 1e6, args.freq / 1e6,
                 args.lo_offset / 1e3, self.rate / 1e6, gain_txt, args.ppm,
                 'ON (4.5 V on the coax)' if args.bias_tee else 'off'))


class Monitor(object):
    """Watches the running flowgraph for the failures that look like silence.

    Polled from the main thread once a second. All three checks are measured
    rather than inferred, because from the packet log alone a Pi that cannot
    keep up, a dongle that has stopped delivering, and a band with nothing on
    it are indistinguishable.
    """

    def __init__(self, rx, args):
        self.rx = rx
        self.status_s = float(args.status)
        self.stall_s = float(args.stall_timeout)
        self.t0 = time.monotonic()
        self.cpu0 = time.process_time()
        self._last_status = self.t0
        self._win_t = None
        self._win_n = 0
        self.lost_s = 0.0
        self._warned_load = False
        self.stalled = False

    def load(self):
        """Process CPU seconds per second of signal, across every thread."""
        n, _, _ = self.rx.sink.snapshot()
        signal_s = n / self.rx.out_rate
        cpu = time.process_time() - self.cpu0
        return cpu / signal_s if signal_s > 0 else 0.0

    def tick(self):
        now = time.monotonic()
        n, _, last = self.rx.sink.snapshot()
        if not self.rx.live:
            return True

        # Stall. Measured from the last sample, or from start-up if none has
        # arrived yet - a dongle that opens but never streams is the same
        # failure as one that stops.
        since = now - (last if last is not None else self.t0)
        if self.stall_s > 0 and since > self.stall_s:
            print('!! No samples from the RTL-SDR for %.0f s. The dongle has '
                  'stopped streaming' % since)
            print('   (unplugged, brown-out, or a wedged USB transfer). '
                  'Exiting so it can be reopened.')
            self.stalled = True
            return False

        # Lost samples. The first window starts at the first sample, so the
        # latency of opening the device is not counted as loss.
        if last is None:
            return True
        if self._win_t is None:
            self._win_t, self._win_n = now, n
        elif now - self._win_t >= 10.0:
            expect = (now - self._win_t) * self.rx.out_rate
            got = n - self._win_n
            # A few percent of slack absorbs GNU Radio's buffering, which
            # delivers in chunks rather than evenly across the window.
            if got < 0.95 * expect:
                gap = (expect - got) / self.rx.out_rate
                self.lost_s += gap
                print('!! ~%.1f s of samples did not arrive in the last %.0f s '
                      '- the chain is not keeping up,'
                      % (gap, now - self._win_t))
                print('   and packets in that gap were never seen. Lower '
                      '--rate (try 250e3 with --lo-offset 50e3).')
            self._win_t, self._win_n = now, n

        load = self.load()
        if load > 0.8 and not self._warned_load:
            self._warned_load = True
            print('!! CPU load %.0f%% of one core per second of signal. This '
                  'Pi is close to not keeping up;' % (load * 100))
            print('   lower --rate (try 250e3 with --lo-offset 50e3) or raise '
                  '--threshold.')

        if self.status_s > 0 and now - self._last_status >= self.status_s:
            self._last_status = now
            print('   [%s  load %.0f%% of one core, %.1f s of signal%s]'
                  % (time.strftime('%H:%M:%S'), load * 100,
                     n / self.rx.out_rate,
                     ', ~%.1f s LOST' % self.lost_s if self.lost_s else ''))
        return True

    def summary(self):
        n, proc, _ = self.rx.sink.snapshot()
        signal_s = n / self.rx.out_rate
        # A replay runs as fast as the CPU allows, with GNU Radio's threads
        # spinning on a source that never waits, so a load figure from it says
        # nothing about real time. si4463_benchmark.py measures that properly.
        if self.rx.live:
            print('\nProcessed %.1f s of signal: %.1f s of CPU across all GNU '
                  'Radio threads (load %.0f%%), %.1f s of it in the decoder.'
                  % (signal_s, time.process_time() - self.cpu0,
                     self.load() * 100, proc))
        else:
            print('\nProcessed %.1f s of signal.' % signal_s)
        if self.rx.sink.errors:
            print('!! The decoder raised %d error(s) and carried on; see the '
                  'tracebacks above.' % self.rx.sink.errors)
        if self.lost_s:
            print('!! About %.1f s of samples were lost because the chain '
                  'could not keep up.' % self.lost_s)
            print('   Packets in those gaps were never seen. Lower --rate or '
                  'raise --threshold.')


def list_devices():
    try:
        import osmosdr
    except ImportError:
        print('gr-osmosdr is not installed:')
        print('    sudo apt install gr-osmosdr')
        return 1
    found = [d.to_string() for d in osmosdr.device.find(osmosdr.device_t('rtl'))]
    rtl = [d for d in found if 'rtl=' in d and 'rtl_tcp' not in d]
    if not rtl:
        print('No RTL-SDR devices found.')
        print('If one is plugged in, the DVB-T driver has probably claimed it:')
        print('    lsmod | grep dvb_usb_rtl28xxu')
        print('Run ./install.sh to blacklist it, then replug the dongle.')
        return 1
    print('RTL-SDR devices:')
    for d in rtl:
        print('  %s' % d)
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(
        prog='si4463_rt',
        description='Real-time Si4463 sensor-packet decoder for RTL-SDR on '
                    'Raspberry Pi, as a headless GNU Radio flowgraph.')
    p.add_argument('-f', '--freq', type=float, default=433.400e6,
                   help='transmitter frequency in Hz (default: 433.400e6, the '
                        'Si4463 at FREQ_CONTROL_INTE=56, FRAC=0x0E4B18, '
                        'outdiv 8)')
    p.add_argument('-r', '--rate', type=float, default=1.2e6,
                   help='SDR sample rate in Hz (default: 1.2e6). The RTL2832 '
                        'supports 225001-300000 and 900001-3200000 only.')
    p.add_argument('--lo-offset', type=float, default=100e3,
                   help='how far above the signal to park the LO, in Hz, to '
                        'keep the DC spike off the packet (default: 100e3)')
    p.add_argument('--ppm', type=float, default=0.0,
                   help='tuner frequency correction in ppm (default: 0, which '
                        'is right for the V3 and its 1 ppm TCXO). The filter '
                        'tolerates tens of kHz of error either way.')
    # Gain defaults to zero: over the ranges this link is used at, the dongle
    # sees far more signal than it can take. +20 dBm out and about 31 dB of
    # free-space loss at 2 m puts roughly -11 dBm on the antenna, and an
    # RTL-SDR front end clips near -10 dBm with no gain at all. Anything on top
    # of that drives the tuner into compression, which raises the noise floor
    # and produces intermodulation - and from the packet log that is
    # indistinguishable from a weak signal. Raise it only until packets are
    # solid, watching the peak level in the heartbeat line: it should sit near
    # 0.5, never pinned at 1.0.
    p.add_argument('-g', '--gain', type=float, default=0.0,
                   help='tuner gain in dB, snapped to the nearest step the '
                        'R820T2 offers (default: 0, see the note in the '
                        'source)')
    p.add_argument('--agc', action='store_true',
                   help='use the tuner AGC instead of a fixed gain; not '
                        'recommended for a 5%% duty cycle signal, because the '
                        'loop hunts during the gap and is still recovering '
                        'when the next preamble arrives')
    p.add_argument('--bias-tee', action='store_true',
                   help='switch on the RTL-SDR Blog V3 bias tee (4.5 V up the '
                        'coax). Off by default, and set explicitly either way '
                        'because the dongle remembers it between sessions.')
    p.add_argument('-d', '--device-index', type=int, default=0,
                   help='which RTL-SDR to use (default: 0)')
    p.add_argument('--device-args', default='',
                   help='extra gr-osmosdr rtl arguments, comma separated, e.g. '
                        '"buffers=32,buflen=65536"')
    p.add_argument('--list-devices', action='store_true',
                   help='list attached RTL-SDRs and exit')
    p.add_argument('-w', '--wav', default=None,
                   help='replay an SDR++ baseband WAV instead of using the SDR')
    p.add_argument('--wav-offset', type=float, default=-12600.0,
                   help='frequency shift for --wav mode in Hz (default: '
                        '-12600, the measured offset of the 26-08-2026 '
                        'recording)')
    p.add_argument('-b', '--baud', type=float, default=10000.0,
                   help='symbol rate (default: 10000)')
    p.add_argument('--deviation', type=float, default=20000.0,
                   help='FSK deviation in Hz (default: 20000)')
    p.add_argument('--packet-len', type=int, default=45,
                   help='payload length in bytes (default: 45)')
    p.add_argument('-t', '--threshold', type=float, default=3.0,
                   help='burst detection threshold above the noise floor, in '
                        'dB (default: 3.0)')
    p.add_argument('--heartbeat', type=float, default=30.0,
                   help='seconds between "still listening" lines, 0 to disable '
                        '(default: 30)')
    p.add_argument('--status', type=float, default=60.0,
                   help='seconds between CPU load lines, 0 to disable '
                        '(default: 60)')
    p.add_argument('--stall-timeout', type=float, default=10.0,
                   help='exit with an error if the RTL-SDR delivers no samples '
                        'for this many seconds, so systemd can restart it; 0 '
                        'to disable (default: 10)')
    p.add_argument('--csv', default=None,
                   help='write the packet log here instead of the default '
                        'logs/packets_<date>_<time>.csv beside this script. '
                        'One row per packet, flushed as it arrives. An '
                        'existing file is appended to, not overwritten.')
    p.add_argument('--no-csv', action='store_true',
                   help='decode to the screen only and write no log file')
    args = p.parse_args(argv)

    if args.list_devices:
        return list_devices()

    # Logging is on unless it is turned off. Packets that were never written
    # down cannot be recovered afterwards, so the safe default keeps them.
    if args.no_csv:
        args.csv = None
    elif args.csv is None:
        args.csv = si4463_csv.default_log_path()

    # The passband has to fit below Nyquist once the LO has been offset, or the
    # filter is selecting a band that is partly folded. This is a real trap at
    # the low sample rates a Pi might want: at 250 kS/s, Nyquist is 125 kHz and
    # the default 100 kHz offset leaves only 25 kHz for a 60 kHz passband.
    if not args.wav:
        nyquist = args.rate / 2.0
        if args.lo_offset + CUTOFF_HZ > nyquist:
            room = max(0.0, nyquist - CUTOFF_HZ)
            sys.stderr.write(
                'error: --lo-offset %.0f kHz plus the %.0f kHz passband '
                'exceeds Nyquist (%.0f kHz)\n'
                '       at --rate %.3f MS/s, so the selected band would be '
                'partly aliased.\n'
                '       Use --lo-offset up to %.0f kHz at this rate, or raise '
                '--rate.\n'
                % (args.lo_offset / 1e3, CUTOFF_HZ / 1e3, nyquist / 1e3,
                   args.rate / 1e6, room / 1e3))
            return 2

    try:
        rx = Receiver(args)
    except ImportError as exc:
        sys.stderr.write('%s\ngr-osmosdr is needed for live decoding:\n'
                         '    sudo apt install gr-osmosdr\n' % exc)
        return 1
    except RuntimeError as exc:
        sys.stderr.write(
            'Could not open the RTL-SDR: %s\n'
            'Check ./si4463_rt.py --list-devices. "usb_claim_interface error '
            '-6" means the DVB-T\ndriver has it: run ./install.sh, then '
            'replug the dongle.\n' % exc)
        return 1

    mon = Monitor(rx, args)
    done = threading.Event()
    stopping = threading.Event()

    def sig_handler(_sig=None, _frame=None):
        stopping.set()

    signal.signal(signal.SIGINT, sig_handler)
    signal.signal(signal.SIGTERM, sig_handler)

    rx.start()
    # wait() returns when a finite source (the WAV) runs out, or after stop().
    threading.Thread(target=lambda: (rx.wait(), done.set()),
                     daemon=True).start()

    while not done.wait(1.0):
        if stopping.is_set() or not mon.tick():
            break

    rx.stop()
    # A wedged USB transfer can leave the osmosdr thread unable to return. The
    # CSV is flushed row by row, so nothing is lost by not waiting forever for
    # it; give the flowgraph a few seconds, then leave regardless.
    if not done.wait(5.0):
        print('!! The flowgraph did not shut down cleanly; exiting anyway.')
        sys.stdout.flush()
        os._exit(1)

    mon.summary()
    return 1 if mon.stalled else 0


if __name__ == '__main__':
    sys.exit(main())
